"""Turn tools/bongo_frames.txt (68x32 frames, '#' = lit pixel) into the LVGL
indexed-1bit images of src/nice_view_rotten/sprites.c.

Lit pixels use the foreground color, which the nice!view shows light on its
dark background (like the stock texts): the cat looks like the classic OLED
one, light body with dark eyes and mouth.

The tap frames of the file are cleaned of their cartoon impact marks and
renamed by the side of the screen their paw is on (tap1 = paw on the left of
the screen, tap0 = paw on the right). Each also gets a "far" copy whose paw
reaches FAR_REACH pixels further from the body (keys of the two top rows).
Every frame is padded to HEIGHT rows.

Usage: python3 tools/sprites.py src/nice_view_rotten/sprites.c
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))


def load_frames():
    frames, name = {}, None
    with open(os.path.join(HERE, "bongo_frames.txt"), encoding="utf-8") as f:
        for line in f.read().splitlines():
            if line.startswith("== "):
                name = line[3:].strip()
                frames[name] = []
            elif line:
                frames[name].append(line)
    return frames


HEIGHT = 34
# Per tap frame: new name, boxes (x0, x1, y0, y1) of the impact marks to
# erase, box of the paw that is down and the direction it reaches out to
TAPS = {
    "tap1": ("tap_left", [(16, 25, 27, 31), (30, 36, 30, 31)], (14, 33, 18, 27), (-1, 1)),
    "tap0": ("tap_right", [(53, 59, 2, 10), (58, 66, 6, 13), (56, 67, 17, 27)], (44, 57, 10, 18), (1, 1)),
}
FAR_REACH = 3


def pad(rows):
    return rows + ["." * len(rows[0])] * (HEIGHT - len(rows))


def erase(rows, boxes):
    grid = [list(r) for r in rows]
    for x0, x1, y0, y1 in boxes:
        for y in range(y0, y1 + 1):
            for x in range(x0, x1 + 1):
                grid[y][x] = "."
    return ["".join(r) for r in grid]


def reach(rows, box, direction):
    """Smear the paw in box FAR_REACH pixels along direction: the arm gets
    longer and the paw lands further from the body."""
    x0, x1, y0, y1 = box
    dx, dy = direction
    grid = [list(r) for r in rows]
    h, w = len(grid), len(grid[0])
    for step in range(1, FAR_REACH + 1):
        for y in range(y0, y1 + 1):
            for x in range(x0, x1 + 1):
                if rows[y][x] == "#":
                    nx, ny = x + dx * step, y + dy * step
                    if 0 <= nx < w and 0 <= ny < h:
                        grid[ny][nx] = "#"
    return ["".join(r) for r in grid]


def build_frames():
    frames = {}
    for name, rows in load_frames().items():
        rows = pad(rows)
        if name in TAPS:
            new_name, marks, paw, direction = TAPS[name]
            rows = erase(rows, marks)
            frames[new_name] = rows
            frames[new_name + "_far"] = reach(rows, paw, direction)
        else:
            frames[name] = rows
    return frames


def to_c(name, rows):
    w, h = len(rows[0]), len(rows)
    stride = (w + 7) // 8
    data = []
    for row in rows:
        for bx in range(stride):
            byte = 0
            for bit in range(8):
                x = bx * 8 + bit
                ink = x < w and row[x] == "#"
                byte = (byte << 1) | (0 if ink else 1)   # bit 1 = background
            data.append(byte)
    body = ",\n    ".join(", ".join(f"0x{b:02x}" for b in data[i:i + 12]) for i in range(0, len(data), 12))
    return f'''
static const LV_ATTRIBUTE_MEM_ALIGN LV_ATTRIBUTE_LARGE_CONST uint8_t bongo_{name}_map[] = {{
    PALETTE
    {body},
}};

const lv_img_dsc_t bongo_{name} = {{
    .header.cf = LV_IMG_CF_INDEXED_1BIT,
    .header.always_zero = 0,
    .header.reserved = 0,
    .header.w = {w},
    .header.h = {h},
    .data_size = {8 + len(data)},
    .data = bongo_{name}_map,
}};
'''


HEAD = '''/*
 * Bongo cat frames of the nice_view_rotten left screen
 * (generated by tools/sprites.py from tools/bongo_frames.txt).
 *
 * The frames are the classic QMK OLED bongo cat by ObliviousGmn (as used in
 * riiadesign/lily58-kiumi), cropped to 68x32 for the nice!view.
 */

#include <lvgl.h>

#ifndef LV_ATTRIBUTE_MEM_ALIGN
#define LV_ATTRIBUTE_MEM_ALIGN
#endif

/* Index 0 = ink, index 1 = background (swapped when the screen is inverted) */
#if CONFIG_NICE_VIEW_ROTTEN_INVERTED
#define PALETTE 0xff, 0xff, 0xff, 0xff, 0x00, 0x00, 0x00, 0xff,
#else
#define PALETTE 0x00, 0x00, 0x00, 0xff, 0xff, 0xff, 0xff, 0xff,
#endif
'''

if __name__ == "__main__":
    frames = build_frames()
    with open(sys.argv[1], "w", encoding="utf-8") as f:
        f.write(HEAD + "".join(to_c(n, rows) for n, rows in frames.items()))
    print(f"{len(frames)} frames written to {sys.argv[1]}")
