"""Turn tools/bongo_frames.txt (68x32 frames, '#' = lit OLED pixel) into the
LVGL indexed-1bit images of src/nice_view_rotten/sprites.c.

The OLED frames are a white cat on black. On the nice!view (dark ink on a
light screen) the cat is drawn the classic way instead: light body, dark
outline, dark eyes and mouth.

Usage: python3 tools/sprites.py src/nice_view_rotten/sprites.c
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))


def load_frames():
    frames, name = {}, None
    with open(os.path.join(HERE, "bongo_frames.txt"), encoding="utf-8") as f:
        for line in f.read().splitlines():
            if line.startswith("== "):
                name = line[3:].strip()
                frames[name] = []
            elif line:
                frames[name].append(line)
    return frames


def outline(rows):
    """Lit pixels next to an unlit one become ink, and so do the unlit holes
    inside the cat (eyes, mouth); the rest of the body stays light."""
    h, w = len(rows), len(rows[0])
    lit = [[c == "#" for c in r] for r in rows]
    outside = set()
    todo = [(x, y) for x in range(w) for y in (0, h - 1)] + [(x, y) for y in range(h) for x in (0, w - 1)]
    while todo:
        x, y = todo.pop()
        if not (0 <= x < w and 0 <= y < h) or (x, y) in outside or lit[y][x]:
            continue
        outside.add((x, y))
        todo += [(x + 1, y), (x - 1, y), (x, y + 1), (x, y - 1)]
    out = []
    for y in range(h):
        row = ""
        for x in range(w):
            if lit[y][x]:
                edge = any(not (0 <= x + dx < w and 0 <= y + dy < h) or (x + dx, y + dy) in outside
                           for dx in (-1, 0, 1) for dy in (-1, 0, 1))
                row += "#" if edge else "."
            else:
                row += "." if (x, y) in outside else "#"
        out.append(row)
    return out


def to_c(name, rows):
    rows = outline(rows)
    w, h = len(rows[0]), len(rows)
    stride = (w + 7) // 8
    data = []
    for row in rows:
        for bx in range(stride):
            byte = 0
            for bit in range(8):
                x = bx * 8 + bit
                ink = x < w and row[x] == "#"
                byte = (byte << 1) | (0 if ink else 1)   # bit 1 = background
            data.append(byte)
    body = ",\n    ".join(", ".join(f"0x{b:02x}" for b in data[i:i + 12]) for i in range(0, len(data), 12))
    return f'''
static const LV_ATTRIBUTE_MEM_ALIGN LV_ATTRIBUTE_LARGE_CONST uint8_t bongo_{name}_map[] = {{
    PALETTE
    {body},
}};

const lv_img_dsc_t bongo_{name} = {{
    .header.cf = LV_IMG_CF_INDEXED_1BIT,
    .header.always_zero = 0,
    .header.reserved = 0,
    .header.w = {w},
    .header.h = {h},
    .data_size = {8 + len(data)},
    .data = bongo_{name}_map,
}};
'''


HEAD = '''/*
 * Bongo cat frames of the nice_view_rotten left screen
 * (generated by tools/sprites.py from tools/bongo_frames.txt).
 *
 * The frames are the classic QMK OLED bongo cat by ObliviousGmn (as used in
 * riiadesign/lily58-kiumi), cropped to 68x32 for the nice!view.
 */

#include <lvgl.h>

#ifndef LV_ATTRIBUTE_MEM_ALIGN
#define LV_ATTRIBUTE_MEM_ALIGN
#endif

/* Index 0 = ink, index 1 = background (swapped when the screen is inverted) */
#if CONFIG_NICE_VIEW_ROTTEN_INVERTED
#define PALETTE 0xff, 0xff, 0xff, 0xff, 0x00, 0x00, 0x00, 0xff,
#else
#define PALETTE 0x00, 0x00, 0x00, 0xff, 0xff, 0xff, 0xff, 0xff,
#endif
'''

frames = load_frames()
with open(sys.argv[1], "w", encoding="utf-8") as f:
    f.write(HEAD + "".join(to_c(n, rows) for n, rows in frames.items()))
print(f"{len(frames)} frames written to {sys.argv[1]}")
