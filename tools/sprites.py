"""Turn tools/bongo_frames.txt (68x32 frames, '#' = lit pixel) and
tools/logos.txt (right screen logos) into the LVGL indexed-1bit images of
src/nice_view_rotten/sprites.c.

Lit pixels use the foreground color, which the nice!view shows light on its
dark background (like the stock texts): the cat looks like the classic OLED
one, light body with dark eyes and mouth.

The tap frames are renamed by the side of the screen their paw is on
(tap1 = paw on the left of the screen, tap0 = paw on the right). Every frame
is padded to HEIGHT rows.

Usage: python3 tools/sprites.py src/nice_view_rotten/sprites.c
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))


def load_frames(file="bongo_frames.txt"):
    frames, name = {}, None
    with open(os.path.join(HERE, file), encoding="utf-8") as f:
        for line in f.read().splitlines():
            if line.startswith("== "):
                name = line[3:].strip()
                frames[name] = []
            elif line:
                frames[name].append(line)
    return frames


HEIGHT = 34
TAPS = {"tap1": "tap_left", "tap0": "tap_right"}


def pad(rows):
    return rows + ["." * len(rows[0])] * (HEIGHT - len(rows))


def build_frames():
    return {TAPS.get(name, name): pad(rows) for name, rows in load_frames().items()}


def build_images():
    """Every image of sprites.c: bongo_* frames, then the logos"""
    images = {"bongo_" + name: rows for name, rows in build_frames().items()}
    images.update(load_frames("logos.txt"))
    return images


def to_c(name, rows):
    w, h = len(rows[0]), len(rows)
    stride = (w + 7) // 8
    data = []
    for row in rows:
        for bx in range(stride):
            byte = 0
            for bit in range(8):
                x = bx * 8 + bit
                ink = x < w and row[x] == "#"
                byte = (byte << 1) | (0 if ink else 1)   # bit 1 = background
            data.append(byte)
    body = ",\n    ".join(", ".join(f"0x{b:02x}" for b in data[i:i + 12]) for i in range(0, len(data), 12))
    return f'''
static const LV_ATTRIBUTE_MEM_ALIGN LV_ATTRIBUTE_LARGE_CONST uint8_t {name}_map[] = {{
    PALETTE
    {body},
}};

const lv_img_dsc_t {name} = {{
    .header.cf = LV_IMG_CF_INDEXED_1BIT,
    .header.always_zero = 0,
    .header.reserved = 0,
    .header.w = {w},
    .header.h = {h},
    .data_size = {8 + len(data)},
    .data = {name}_map,
}};
'''


HEAD = '''/*
 * Images of the nice_view_rotten screens (generated by tools/sprites.py from
 * tools/bongo_frames.txt and tools/logos.txt).
 *
 * The bongo cat frames are the classic QMK OLED bongo cat by ObliviousGmn (as
 * used in riiadesign/lily58-kiumi), cropped to 68x32 for the nice!view. The
 * right screen shows the Arch Linux logo and an atom symbol in a ring.
 */

#include <lvgl.h>

#ifndef LV_ATTRIBUTE_MEM_ALIGN
#define LV_ATTRIBUTE_MEM_ALIGN
#endif

/* Index 0 = ink, index 1 = background (swapped when the screen is inverted) */
#if CONFIG_NICE_VIEW_ROTTEN_INVERTED
#define PALETTE 0xff, 0xff, 0xff, 0xff, 0x00, 0x00, 0x00, 0xff,
#else
#define PALETTE 0x00, 0x00, 0x00, 0xff, 0xff, 0xff, 0xff, 0xff,
#endif
'''

if __name__ == "__main__":
    images = build_images()
    with open(sys.argv[1], "w", encoding="utf-8") as f:
        f.write(HEAD + "".join(to_c(n, rows) for n, rows in images.items()))
    print(f"{len(images)} images written to {sys.argv[1]}")
