"""Draw the 1-bit sprites for the nice!view (bongo cat frames, rotten flesh)
and write them as LVGL indexed-1bit C arrays + PNG previews."""
import sys
from PIL import Image, ImageDraw

out_c, out_dir = sys.argv[1], sys.argv[2]


def cat(paws):
    """Bongo cat, 60x46, sitting behind a table. paws: (left_down, right_down)."""
    w, h = 60, 46
    im = Image.new("1", (w, h), 1)
    d = ImageDraw.Draw(im)
    # head / body: a dome resting on the table
    d.arc([8, 6, 52, 58], 180, 360, fill=0, width=2)
    d.line([(8, 32), (8, 40)], fill=0, width=2)
    d.line([(51, 32), (51, 37)], fill=0, width=2)
    # ears
    d.line([(13, 17), (15, 4), (24, 10)], fill=0, width=2)
    d.line([(36, 9), (45, 3), (47, 16)], fill=0, width=2)
    # eyes ("^ ^") and mouth ("w")
    d.line([(19, 22), (22, 19), (25, 22)], fill=0)
    d.line([(35, 21), (38, 18), (41, 21)], fill=0)
    d.line([(26, 27), (28, 29), (30, 27), (32, 29), (34, 27)], fill=0)
    # table
    d.line([(0, 43), (59, 37)], fill=0, width=2)
    left_down, right_down = paws
    if left_down:          # paw slammed on the table
        d.ellipse([11, 34, 23, 42], fill=0)
    else:                  # paw raised
        d.line([(12, 33), (6, 24)], fill=0, width=2)
        d.ellipse([1, 17, 9, 25], fill=1, outline=0)
    if right_down:
        d.ellipse([38, 31, 50, 39], fill=0)
    else:
        d.line([(47, 31), (53, 22)], fill=0, width=2)
        d.ellipse([50, 15, 58, 23], fill=1, outline=0)
    return im


ROTTEN_FLESH = [
    # 16x16 Minecraft-like rotten flesh: '#' = ink, 'o' = light speckle, '.' = background
    "..........####..",
    "........###o###.",
    ".......##o####o#",
    "......####o##o##",
    ".....##o#####o#.",
    "....###o##o####.",
    "...#o####o##o#..",
    "..####o####o##..",
    ".##o####o####...",
    ".#####o###o##...",
    "##o#######o#....",
    "#####o#o####....",
    "#o#######o#.....",
    ".###o####.......",
    "..#####.........",
    "...##...........",
]


def flesh():
    im = Image.new("1", (16, 16), 1)
    for y, row in enumerate(ROTTEN_FLESH):
        for x, c in enumerate(row):
            if c == "#":
                im.putpixel((x, y), 0)
    return im.resize((32, 32), Image.NEAREST)


def to_c(name, im):
    w, h = im.size
    stride = (w + 7) // 8
    data = []
    for y in range(h):
        for bx in range(stride):
            byte = 0
            for bit in range(8):
                x = bx * 8 + bit
                v = im.getpixel((x, y)) if x < w else 1   # 1 = background
                byte = (byte << 1) | (1 if v else 0)
            data.append(byte)
    rows = ",\n    ".join(", ".join(f"0x{b:02x}" for b in data[i:i + 12]) for i in range(0, len(data), 12))
    return f'''
static const LV_ATTRIBUTE_MEM_ALIGN LV_ATTRIBUTE_LARGE_CONST uint8_t {name}_map[] = {{
    PALETTE
    {rows},
}};

const lv_img_dsc_t {name} = {{
    .header.cf = LV_IMG_CF_INDEXED_1BIT,
    .header.always_zero = 0,
    .header.reserved = 0,
    .header.w = {w},
    .header.h = {h},
    .data_size = {8 + len(data)},
    .data = {name}_map,
}};
'''


sprites = {
    "bongo_idle": cat((False, False)),
    "bongo_left": cat((True, False)),
    "bongo_right": cat((False, True)),
    "rotten_flesh": flesh(),
}

head = '''/*
 * Copyright (c) 2026 PoUrRiTuRe
 * SPDX-License-Identifier: MIT
 *
 * 1-bit sprites of the nice_view_rotten screens (generated by tools/sprites.py)
 */

#include <lvgl.h>

#ifndef LV_ATTRIBUTE_MEM_ALIGN
#define LV_ATTRIBUTE_MEM_ALIGN
#endif

/* Index 0 = ink, index 1 = background (swapped when the screen is inverted) */
#if CONFIG_NICE_VIEW_ROTTEN_INVERTED
#define PALETTE 0xff, 0xff, 0xff, 0xff, 0x00, 0x00, 0x00, 0xff,
#else
#define PALETTE 0x00, 0x00, 0x00, 0xff, 0xff, 0xff, 0xff, 0xff,
#endif
'''
with open(out_c, "w") as f:
    f.write(head + "".join(to_c(n, im) for n, im in sprites.items()))

for n, im in sprites.items():
    im.convert("L").resize((im.size[0] * 6, im.size[1] * 6), Image.NEAREST).save(f"{out_dir}/{n}.png")
print("ok")
